window.currentLang = localStorage.getItem('acx_lang') || 'ru';

window.t = function(key) {
  return ACX_LANG[currentLang]?.[key] || ACX_LANG.ru[key] || key;
};

window.setLang = function(lang) {
  if (!ACX_LANG[lang]) return;
  currentLang = lang;
  localStorage.setItem('acx_lang', lang);
  applyLang();
};

window.applyLang = function() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const text = t(key);
    if (el.tagName === 'INPUT' && el.type !== 'text') return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = text;
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = t(key);
  });
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'ru';

  // Update lang selector if exists
  const ls = document.getElementById('lang-select');
  if (ls) ls.value = currentLang;
};

// Auto-apply on load
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => applyLang());
} else {
  applyLang();
}
